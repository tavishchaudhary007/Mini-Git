#!/usr/bin/env python3
"""Regenerate include/FrontendTemplate.h from templates/frontend.html.

Only needed after you edit templates/frontend.html:
    python tools/embed_frontend.py
"""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
html = (root / "templates" / "frontend.html").read_text(encoding="utf-8").replace("\r\n", "\n")
delim = "MGHTML"
assert f"){delim}\"" not in html, "template contains the raw-string terminator"

CHUNK_SIZE = 50000
chunks = [html[i:i + CHUNK_SIZE] for i in range(0, len(html), CHUNK_SIZE)]

chunks_code = []
for chunk in chunks:
    chunks_code.append(f'    R"{delim}({chunk}){delim}"')

chunks_joined = ",\n".join(chunks_code)

out = f"""// AUTO-GENERATED by tools/embed_frontend.py from templates/frontend.html -- do not edit by hand.
#pragma once
#include <string>

inline const char* const kFrontendChunks[] = {{
{chunks_joined}
}};

inline const std::string kFrontendTemplate = []() {{
    std::string s;
    s.reserve({len(html) + 1024});
    for (const char* chunk : kFrontendChunks) {{
        s.append(chunk);
    }}
    return s;
}}();
"""
(root / "include" / "FrontendTemplate.h").write_text(out, encoding="utf-8", newline="\n")
print(f"wrote include/FrontendTemplate.h ({len(html)} bytes of HTML in {len(chunks)} chunks)")
